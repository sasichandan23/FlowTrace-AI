"""Create demo employee accounts.

Writes config/employees.json (salted PBKDF2 hashes only) and DEMO_CREDENTIALS.md
(plain demo passwords for the hackathon judges – delete it for any real use).

    python scripts/seed_employees.py
"""
import json
import secrets
import string
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from core.auth import hash_password  # noqa: E402
from core.config import BANKS, EMPLOYEES_FILE, ROOT  # noqa: E402

EMPLOYEES = [
    ("NWB-AN-101", "Northwind AML Analyst", "NWB", "analyst"),
    ("NWB-IN-201", "Northwind AML Investigator", "NWB", "investigator"),
    ("MTB-AN-102", "Meridian AML Analyst", "MTB", "analyst"),
    ("MTB-IN-202", "Meridian AML Investigator", "MTB", "investigator"),
    ("CFB-AN-103", "Crescent AML Analyst", "CFB", "analyst"),
    ("CFB-IN-203", "Crescent AML Investigator", "CFB", "investigator"),
    ("HQ-CO-001", "Group Compliance Officer", "NWB", "admin"),
]


def make_password() -> str:
    alphabet = string.ascii_letters + string.digits
    return "Ft-" + "".join(secrets.choice(alphabet) for _ in range(8)) + "!"


def main() -> None:
    records, lines = [], []
    for emp_id, name, bank, role in EMPLOYEES:
        pw = make_password()
        salt, digest = hash_password(pw)
        records.append({"employee_id": emp_id, "name": name, "bank_id": bank, "role": role,
                        "salt": salt, "password_hash": digest, "active": True})
        scope = "All banks" if role == "admin" else BANKS[bank]
        lines.append(f"| `{emp_id}` | `{pw}` | {role} | {scope} |")
    EMPLOYEES_FILE.parent.mkdir(parents=True, exist_ok=True)
    EMPLOYEES_FILE.write_text(json.dumps(records, indent=2), encoding="utf-8")
    (ROOT / "DEMO_CREDENTIALS.md").write_text(
        "# Demo credentials (hackathon only)\n\n"
        "Generated by `scripts/seed_employees.py`. Only salted hashes are stored in `config/employees.json`.\n"
        "Re-run the script to rotate all passwords. **Delete this file for any real deployment.**\n\n"
        "| Employee ID | Password | Role | Data scope |\n|---|---|---|---|\n" + "\n".join(lines) + "\n\n"
        "- **analyst** – overview, risk ranking, network, data quality, exports (own bank only)\n"
        "- **investigator** – analyst access + customer history / investigation reports + transfer graph\n"
        "- **admin** – everything, all banks, audit log\n",
        encoding="utf-8")
    print(f"Wrote {len(records)} employees to {EMPLOYEES_FILE} and DEMO_CREDENTIALS.md")


if __name__ == "__main__":
    main()
